import 'package:flutter/material.dart';
import 'dart:io';
import 'package:path_provider/path_provider.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import '../../data/models/plot_input_model.dart';
import '../../data/models/cost_estimation_model.dart';
import '../viewmodels/plot_input_viewmodel.dart';

class ExportViewModel extends ChangeNotifier {
  bool _isLoading = false;
  String? _errorMessage;
  bool _success = false;
  String? _savedPath;

  bool get isLoading => _isLoading;
  String? get errorMessage => _errorMessage;
  bool get success => _success;
  String? get savedPath => _savedPath;

  void reset() {
    _isLoading = false;
    _errorMessage = null;
    _success = false;
    _savedPath = null;
    notifyListeners();
  }

  Future<void> exportPdf({
    required String projectName,
    required String ownerName,
    required PlotInputViewModel plotVm,
    required CostEstimationModel costData,
  }) async {
    _isLoading = true;
    _errorMessage = null;
    _success = false;
    notifyListeners();

    try {
      // Create PDF document
      final pdf = pw.Document();

      // Add first page - Cover
      pdf.addPage(
        pw.Page(
          build: (pw.Context context) {
            return pw.Center(
              child: pw.Column(
                mainAxisAlignment: pw.MainAxisAlignment.center,
                children: [
                  pw.Text(
                    'DOMEXA',
                    style: pw.TextStyle(
                      fontSize: 48,
                      fontWeight: pw.FontWeight.bold,
                      color: PdfColors.blue900,
                    ),
                  ),
                  pw.SizedBox(height: 20),
                  pw.Text(
                    'Construction Report',
                    style: pw.TextStyle(fontSize: 24, color: PdfColors.grey700),
                  ),
                  pw.SizedBox(height: 40),
                  pw.Text(
                    projectName,
                    style: pw.TextStyle(fontSize: 18, fontWeight: pw.FontWeight.bold),
                  ),
                  pw.SizedBox(height: 10),
                  if (ownerName.isNotEmpty)
                    pw.Text('Owner: $ownerName', style: pw.TextStyle(fontSize: 14)),
                  pw.SizedBox(height: 40),
                  pw.Text(
                    'Generated by Domexa AI',
                    style: pw.TextStyle(fontSize: 12, color: PdfColors.grey500),
                  ),
                  pw.Text(
                    '${DateTime.now().day}/${DateTime.now().month}/${DateTime.now().year}',
                    style: pw.TextStyle(fontSize: 12, color: PdfColors.grey500),
                  ),
                ],
              ),
            );
          },
        ),
      );

      // Second page - Project Summary
      pdf.addPage(
        pw.Page(
          build: (pw.Context context) {
            return pw.Padding(
              padding: const pw.EdgeInsets.all(20),
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text(
                    'Project Summary',
                    style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold),
                  ),
                  pw.SizedBox(height: 20),
                  _buildInfoRow('Project Name', projectName),
                  _buildInfoRow('Owner', ownerName.isEmpty ? 'Not specified' : ownerName),
                  _buildInfoRow('Plot Area', '${plotVm.plotArea.toInt()} sq ft'),
                  _buildInfoRow('Marla', '${(plotVm.plotArea / 225).toStringAsFixed(1)} Marla'),
                  _buildInfoRow('Floors', '${plotVm.numFloors}'),
                  _buildInfoRow('Bedrooms', '${plotVm.bedrooms}'),
                  _buildInfoRow('Bathrooms', '${plotVm.bathrooms}'),
                  _buildInfoRow('Style', plotVm.houseStyle.toUpperCase()),
                  pw.SizedBox(height: 20),
                  pw.Text(
                    'Room Features',
                    style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold),
                  ),
                  pw.SizedBox(height: 10),
                  _buildInfoRow('Drawing Room', plotVm.hasDrawingRoom ? 'Yes' : 'No'),
                  _buildInfoRow('Dining Room', plotVm.hasDiningRoom ? 'Yes' : 'No'),
                  _buildInfoRow('Garage', plotVm.hasGarage ? 'Yes' : 'No'),
                  _buildInfoRow('Basement', plotVm.hasBasement ? 'Yes' : 'No'),
                ],
              ),
            );
          },
        ),
      );

      // Third page - Cost Breakdown
      pdf.addPage(
        pw.Page(
          build: (pw.Context context) {
            final builtArea = plotVm.plotArea * 0.7 * plotVm.numFloors;

            return pw.Padding(
              padding: const pw.EdgeInsets.all(20),
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text(
                    'Cost Estimation',
                    style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold),
                  ),
                  pw.SizedBox(height: 20),
                  _buildInfoRow('Built Area', '${builtArea.toInt()} sq ft'),
                  _buildInfoRow('Total Cost', _formatCurrency(costData.totalCost)),
                  _buildInfoRow('Grey Structure', _formatCurrency(costData.greyStructureCost)),
                  _buildInfoRow('Finishing', _formatCurrency(costData.finishingCost)),
                  _buildInfoRow('Labor', _formatCurrency(costData.laborCost)),
                  pw.SizedBox(height: 20),
                  pw.Text(
                    'Additional Notes',
                    style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold),
                  ),
                  pw.SizedBox(height: 10),
                  pw.Text(
                    '• Add 15% contingency for unforeseen expenses',
                    style: pw.TextStyle(fontSize: 12),
                  ),
                  pw.Text(
                    '• WAPDA, gas, and PTCL connections billed separately',
                    style: pw.TextStyle(fontSize: 12),
                  ),
                  pw.Text(
                    '• Architect fees not included (typically 3-5%)',
                    style: pw.TextStyle(fontSize: 12),
                  ),
                ],
              ),
            );
          },
        ),
      );

      // Save PDF
      final directory = await getApplicationDocumentsDirectory();
      final filePath = '${directory.path}/Domexa_${projectName.replaceAll(' ', '_')}.pdf';
      final file = File(filePath);
      await file.writeAsBytes(await pdf.save());

      _savedPath = filePath;
      _success = true;
      _isLoading = false;
      notifyListeners();
    } catch (e) {
      _errorMessage = 'Failed to generate PDF: $e';
      _isLoading = false;
      _success = false;
      notifyListeners();
    }
  }

  pw.Widget _buildInfoRow(String label, String value) {
    return pw.Padding(
      padding: const pw.EdgeInsets.symmetric(vertical: 4),
      child: pw.Row(
        children: [
          pw.SizedBox(
            width: 120,
            child: pw.Text(
              label,
              style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 12),
            ),
          ),
          pw.Expanded(
            child: pw.Text(value, style: pw.TextStyle(fontSize: 12)),
          ),
        ],
      ),
    );
  }

  String _formatCurrency(double amount) {
    if (amount >= 10000000) {
      return 'PKR ${(amount / 10000000).toStringAsFixed(2)} Cr';
    } else if (amount >= 100000) {
      return 'PKR ${(amount / 100000).toStringAsFixed(2)} Lac';
    }
    return 'PKR ${amount.toStringAsFixed(0)}';
  }
}